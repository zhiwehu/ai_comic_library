/** 站内链接：en 语言加 /en 前缀 */
export function href(lang: Lang, path: string): string {
  const p = path.startsWith('/') ? path : `/${path}`;
  return lang === DEFAULT_LANG ? p : `/en${p === '/' ? '/' : p}`;
}

